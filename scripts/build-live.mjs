// Bundles src/lib/liveServer.ts for the "live" Edge Function: node scripts/build-live.mjs
// The result is committed, and a test checks that it is up to date.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const at = (p) => fileURLToPath(new URL("../" + p, import.meta.url));
export const OUT = at("supabase/functions/live/core.js");

export async function bundle() {
  const res = await build({
    configFile: false,
    envFile: false,
    publicDir: false,
    logLevel: "silent",
    build: { write: false, minify: false, target: "es2022", lib: { entry: at("src/lib/liveEntry.ts"), formats: ["es"], fileName: "core" } },
  });
  const code = (Array.isArray(res) ? res[0] : res).output[0].code;
  return "// Generated by scripts/build-live.mjs from src/lib/liveServer.ts. Do not edit.\n" + code.replace(/\r\n/g, "\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url).toLowerCase() === process.argv[1].toLowerCase()) writeFileSync(OUT, await bundle());
